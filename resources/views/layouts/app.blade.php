<script>
    $(function () {
        // ── Mobile sidebar drawer ──
        const $sidebar = $('#sidebar'), $backdrop = $('#sidebar-backdrop'), $toggle = $('#sidebar-toggle');
        const mq = window.matchMedia('(min-width: 1024px)');
        function sidebarOpen() { return !$sidebar.hasClass('-translate-x-full'); }
        function syncSidebar() {
            const open = sidebarOpen();
            $backdrop.toggleClass('hidden', !open);
            $toggle.attr('aria-expanded', open ? 'true' : 'false');
            // Off-canvas drawer must not be tabbable while closed on small screens.
            if (mq.matches || open) $sidebar.removeAttr('inert'); else $sidebar.attr('inert', '');
        }
        function setSidebar(open, returnFocus) {
            $sidebar.toggleClass('-translate-x-full', !open);
            syncSidebar();
            if (open) $sidebar.find('a').first().trigger('focus');
            else if (returnFocus) $toggle.trigger('focus');
        }
        $toggle.on('click', function () { setSidebar(!sidebarOpen()); });
        $backdrop.on('click', function () { setSidebar(false); });
        $sidebar.on('click', 'a', function () { if (!mq.matches) setSidebar(false); });
        if (mq.addEventListener) mq.addEventListener('change', syncSidebar);
        syncSidebar();

        // ── Dropdowns (notifications + user menu) ──
        const dropdowns = [
            { btn: '#notif-btn', dd: '#notif-dd' },
            { btn: '#user-menu-btn', dd: '#user-menu-dropdown' },
        ];
        function closeDropdowns(except, returnFocus) {
            dropdowns.forEach(function (d) {
                if (except === d.dd) return;
                const wasOpen = !$(d.dd).hasClass('hidden');
                $(d.dd).addClass('hidden');
                $(d.btn).attr('aria-expanded', 'false');
                if (wasOpen && returnFocus) $(d.btn).trigger('focus');
            });
        }
        dropdowns.forEach(function (d) {
            $(d.btn).on('click', function (e) {
                e.stopPropagation();
                const open = $(d.dd).hasClass('hidden');
                closeDropdowns(d.dd);
                $(d.dd).toggleClass('hidden', !open);
                $(d.btn).attr('aria-expanded', open ? 'true' : 'false');
            });
            $(d.dd).on('click', function (e) { e.stopPropagation(); });
        });
        $(document).on('click', function () { closeDropdowns(); });
        $(document).on('keydown', function (e) {
            if (e.key !== 'Escape') return;
            if ($('.modal-root:not(.hidden)').length) return;
            closeDropdowns(null, true);
            if (!mq.matches && sidebarOpen()) setSidebar(false, true);
        });

        // Theme (light/dark) + black & white toggles, persisted in localStorage.
        $('#theme-toggle').on('click', function () {
            var root = document.documentElement;
            var cur = root.getAttribute('data-theme')
                || (window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
            var next = cur === 'dark' ? 'light' : 'dark';
            root.setAttribute('data-theme', next);
            localStorage.setItem('erp-theme', next);
        });
        $('#mono-toggle').on('click', function () {
            var root = document.documentElement;
            if (root.getAttribute('data-mono') === '1') { root.removeAttribute('data-mono'); localStorage.setItem('erp-mono', '0'); }
            else { root.setAttribute('data-mono', '1'); localStorage.setItem('erp-mono', '1'); }
        });
        $('#logout-btn').on('click', function () {
            window.http({ method: 'POST', url: '{{ route('logout') }}', quiet: true })
                .done(function (res) { window.location = (res.data && res.data.redirect) || '{{ route('login') }}'; });
        });

        // Notifications bell
        window.loadNotifs = function () {
            $.getJSON('{{ route('notifications.index') }}').done(function (res) {
                const d = res.data || {};
                if (d.unread > 0) $('#notif-badge').removeClass('hidden').text(d.unread > 9 ? '9+' : d.unread);
                else $('#notif-badge').addClass('hidden');
                $('#notif-btn').attr('aria-label', d.unread > 0 ? 'Notifications (' + d.unread + ' unread)' : 'Notifications');
                const items = d.items || [];
                $('#notif-list').html(items.length ? items.map(n => `
                    <a href="${esc(safeUrl(n.url))}" class="block px-4 py-2 border-b" style="border-color:var(--c-neutral-100);${n.read ? '' : 'background:var(--c-accent-50)'}">
                        <div class="font-medium text-sm">${esc(n.title)}</div>
                        <div class="text-xs" style="color:var(--text-muted)">${esc(n.message)} · ${esc(n.at)}</div>
                    </a>`).join('') : '<div class="p-4 text-center text-sm" style="color:var(--text-muted)">You\'re all caught up</div>');
            });
        };
        $('#notif-read').on('click', function () { window.http({ method: 'POST', url: '{{ route('notifications.read') }}', quiet: true }).done(loadNotifs); });
        loadNotifs();
        setInterval(loadNotifs, 30000);
    });
</script>
